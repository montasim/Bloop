import { makeLevel, type LevelDef } from '../level.ts'

// Level 21, first of chapter 5: echoes. Every challenge shows up once in a safe form (a dry ditch under it),
// then comes back as its echo: over thorns, upside down, through the other colour, with a crate or a beetle.
// Inverted stretches are closed by 'D' columns on both sides; crate pens are fenced by a colour column you
// pass through and the crate can't, so a crate can always be pushed back.
